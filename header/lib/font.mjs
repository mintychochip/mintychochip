export const GLYPH_ROWS = 9;

function glyph(ch) {
  const g = GLYPHS[ch];
  if (!g) throw new Error(`font has no glyph for "${ch}"`);
  return g;
}

export function textWidth(text, scale = 1) {
  let w = 0;
  for (const ch of text) w += glyph(ch)[0].length + 1;
  return (w - 1) * scale;
}

// Calls plot(x, y, row) for every lit pixel; row is the pixel's row within
// the scaled glyph cell, for vertical gradients.
export function drawText(text, x, y, scale, plot) {
  let cx = x;
  for (const ch of text) {
    const rows = glyph(ch);
    for (let gy = 0; gy < GLYPH_ROWS; gy++) {
      for (let gx = 0; gx < rows[gy].length; gx++) {
        if (rows[gy][gx] !== '#') continue;
        for (let sy = 0; sy < scale; sy++) {
          for (let sx = 0; sx < scale; sx++) plot(cx + gx * scale + sx, y + gy * scale + sy, gy * scale + sy);
        }
      }
    }
    cx += (rows[0].length + 1) * scale;
  }
}

