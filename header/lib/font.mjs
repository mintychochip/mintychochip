function tiny(ch) {
  const g = TINY[ch] ?? TINY[ch.toLowerCase()];
  if (!g) throw new Error(`tiny font has no glyph for "${ch}"`);
  return g;
}

// Calls plot(x, y) for every lit pixel; (x, y) is the top-left of row 0 of the
// first glyph.
export function drawTiny(text, x, y, plot) {
  let cx = x;
  for (const ch of text) {
    const rows = tiny(ch);
    rows.forEach((row, gy) => {
      for (let gx = 0; gx < row.length; gx++) if (row[gx] === '#') plot(cx + gx, y + gy);
    });
    cx += rows[0].length + 1;
  }
}
